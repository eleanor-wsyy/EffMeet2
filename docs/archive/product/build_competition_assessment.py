def table(headers, rows, widths):
    t=d.add_table(rows=1, cols=len(headers))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.autofit=False
    for c,w in zip(t.columns,widths): c.width=Cm(w)
    for c,text in zip(t.rows[0].cells,headers): c.text=text
    trpr=t.rows[0]._tr.get_or_add_trPr()
    el=OxmlElement('w:tblHeader'); trpr.append(el)
    for row in rows:
        for c,text in zip(t.add_row().cells,row): c.text=text
    borders=OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        el=OxmlElement('w:'+edge)
        for k,v in [('val','single'),('sz','4'),('color','D9D9D9')]: el.set(qn('w:'+k),v)
        borders.append(el)
    t._tbl.tblPr.append(borders)
    for i,row in enumerate(t.rows):
        no=OxmlElement('w:cantSplit'); row._tr.get_or_add_trPr().append(no)
        for j,c in enumerate(row.cells):
            c.width=Cm(widths[j]); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr=c._tc.get_or_add_tcPr()
            sh=OxmlElement('w:shd'); sh.set(qn('w:fill'),'DCE6F1' if i==0 else ('F5F7F9' if i%2==0 else 'FFFFFF')); pr.append(sh)
            mar=OxmlElement('w:tcMar')
            for edge in ['top','left','bottom','right']:
                e=OxmlElement('w:'+edge); e.set(qn('w:w'),'90'); e.set(qn('w:type'),'dxa'); mar.append(e)
            pr.append(mar)
            for para in c.paragraphs:
                para.paragraph_format.space_after=Pt(3)
                para.paragraph_format.line_spacing=1.12
                for r in para.runs: r.font.size=Pt(9); r.bold=(i==0)
    p('')
def link(label,url):
    para=d.add_paragraph()
    hyp=OxmlElement('w:hyperlink')
    from docx.opc.constants import RELATIONSHIP_TYPE as RT
    hyp.set(qn('r:id'),para.part.relate_to(url,RT.HYPERLINK,is_external=True))
    r=OxmlElement('w:r'); pr=OxmlElement('w:rPr')
    color=OxmlElement('w:color'); color.set(qn('w:val'),'245A81'); pr.append(color); r.append(pr)
    txt=OxmlElement('w:t'); txt.text=label; r.append(txt); hyp.append(r); para._p.append(hyp)

